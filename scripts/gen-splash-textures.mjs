// Generates public/walls/splash-*.webp + src/app/wall-splashes.css: full-bleed "paint" wall textures inspired by
// Melissa Barbanti's canvases. All styles share one red/gold base palette; the site
// hue-rotates them (CSS filter) to match the chosen wall color, see src/lib/wall-fantasy.ts.
// Run: node scripts/gen-splash-textures.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { pour } from "./splash-pour.mjs";
import { marble, petals, veins } from "./splash-shapes.mjs";
import { brush, cells, splatter, watercolor } from "./splash-shapes2.mjs";
import { cosmo, materia } from "./splash-shapes3.mjs";

const PALETTE = {
  blobs: ["#c4121f", "#8e0b1a", "#e23a3a", "#1a0a0c"],
  pale: ["#a8707c", "#9a4a63", "#7a2a4a"],
  vein: "#d9a94a",
  specks: ["#d9a94a", "#c9a0a0", "#e23a3a"],
};

const STYLES = {
  pour: [pour, 11],
  petals: [petals, 23],
  marble: [marble, 41],
  veins: [veins, 67],
  splatter: [splatter, 71],
  brush: [brush, 83],
  cells: [cells, 97],
  watercolor: [watercolor, 101],
  materia: [materia, 113],
  cosmo: [cosmo, 127],
};

const OUT_DIR = new URL("../public/walls/", import.meta.url);
mkdirSync(OUT_DIR, { recursive: true });

// The SVGs use heavy filters (turbulence/displacement); rasterizing them once keeps scrolling smooth
// and stops mobile browsers from re-rendering them whenever the viewport changes.
let css = "/* GENERATED by scripts/gen-splash-textures.mjs — paint wall textures. Edit the generator, not this file. */\n";
for (const [name, [build, seed]] of Object.entries(STYLES)) {
  const file = `splash-${name}.webp`;
  const svg = build({ seed, ...PALETTE }).replace("<svg ", '<svg width="1600" height="1000" ');
  await sharp(Buffer.from(svg)).webp({ quality: 82 }).toFile(fileURLToPath(new URL(file, OUT_DIR)));
  css += `.wall[data-texture="splash-${name}"]::after {\n  background-image: url("/walls/${file}");\n  background-size: cover;\n  background-position: center;\n  background-repeat: no-repeat;\n}\n`;
}
writeFileSync(new URL("../src/app/wall-splashes.css", import.meta.url), css);
console.log("wrote wall-splashes.css and public/walls/*.webp");
