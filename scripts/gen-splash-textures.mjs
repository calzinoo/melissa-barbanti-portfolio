// Generates src/app/wall-splashes.css: full-bleed "paint" SVG wall textures inspired by
// Melissa Barbanti's canvases. All styles share one red/gold base palette; the site
// hue-rotates them (CSS filter) to match the chosen wall color, see src/lib/wall-fantasy.ts.
// Run: node scripts/gen-splash-textures.mjs
import { writeFileSync } from "node:fs";
import { pour } from "./splash-pour.mjs";
import { marble, petals, veins } from "./splash-shapes.mjs";
import { brush, cells, splatter, watercolor } from "./splash-shapes2.mjs";
import { cosmo, materia } from "./splash-shapes3.mjs";

const PALETTE = {
  blobs: ["#c4121f", "#8e0b1a", "#e23a3a", "#1a0a0c"],
  pale: ["#f3e6e4", "#d9a7b6", "#7a2a4a"],
  vein: "#d9a94a",
  specks: ["#d9a94a", "#f3e6e4", "#e23a3a"],
};

const STYLES = {
  pour: [pour, 11],
  petals: [petals, 23],
  marble: [marble, 41],
  veins: [veins, 67],
  splatter: [splatter, 71],
  brush: [brush, 83],
  cells: [cells, 97],
  watercolor: [watercolor, 101],
  materia: [materia, 113],
  cosmo: [cosmo, 127],
};

const encode = (svg) =>
  svg.replace(/%/g, "%25").replace(/#/g, "%23").replace(/</g, "%3C").replace(/>/g, "%3E").replace(/"/g, "'");

let css = "/* GENERATED by scripts/gen-splash-textures.mjs — paint wall textures. Edit the generator, not this file. */\n";
for (const [name, [build, seed]] of Object.entries(STYLES)) {
  css += `.wall[data-texture="splash-${name}"]::after {\n  background-image: url("data:image/svg+xml,${encode(build({ seed, ...PALETTE }))}");\n  background-size: cover;\n  background-position: center;\n  background-repeat: no-repeat;\n}\n`;
}
writeFileSync(new URL("../src/app/wall-splashes.css", import.meta.url), css);
console.log("wrote wall-splashes.css", (css.length / 1024).toFixed(0) + " KB");
